/**
 * THE CUTE REPORT for every amigurumi preset (cute-engine plan step 3).
 *
 * Compiles every designer preset (and the dolls, and the cow with its opt-in
 * step-2 shapes) through the same build + relax + audit the render uses and
 * prints the cute check that `compileComposition` attaches
 * (`CompiledComposition.cute`, cuteCheck.ts): per preset a summary line and
 * its failures in plain words. A report: nothing here fails.
 *
 *   cd apps/web && pnpm exec tsx --conditions react-server scripts/loom-cute-report.ts [--bases=bear,cow] [--json=<dir>]
 *   cd apps/web && pnpm exec tsx scripts/loom-cute-report.ts --md=<report.md> --json=<dir>
 *
 * With --json each preset's report is written to <dir>/<label>.json (run
 * several base lists in parallel), and --md assembles a preset x rule table
 * from that directory.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { compileComposition } from '../src/lib/loom/crochet/engine/composition'
import { allPresetChoices, buildAmigurumiProgram, type AmigurumiChoices } from '../src/lib/loom/crochet/engine/amigurumiPresets'
import { dollPresetChoices } from '../src/lib/loom/crochet/engine/doll'
import { CUTE_RULES } from '../src/lib/loom/crochet/engine/cuteRules'
import type { CuteReport } from '../src/lib/loom/crochet/engine/cuteCheck'

const arg = (k: string): string | undefined => process.argv.find((a) => a.startsWith(`--${k}=`))?.slice(k.length + 3)

interface Row { label: string; hash: string; problems: number; cute: CuteReport }

/** Every preset, plus the cow M with the step-2 shapes on. */
function presets(): { label: string; choices: AmigurumiChoices }[] {
  const out = allPresetChoices().map((c) => ({ label: `${c.base}-${c.size}`, choices: c }))
  for (const d of dollPresetChoices()) out.push({ label: `doll-${d.size}`, choices: d as unknown as AmigurumiChoices })
  const cowM = allPresetChoices().find((c) => c.base === 'cow' && c.size === 'M')!
  out.push({ label: 'cow-M+folded', choices: { ...cowM, foldedEars: true } })
  out.push({ label: 'cow-M+horns+legs', choices: { ...cowM, curvedHorns: true, taperedLegs: true } })
  out.push({ label: 'cow-M+all-three', choices: { ...cowM, foldedEars: true, curvedHorns: true, taperedLegs: true } })
  return out
}

function run(): void {
  const bases = arg('bases')?.split(',')
  const dir = arg('json')
  if (dir) mkdirSync(dir, { recursive: true })
  for (const { label, choices } of presets()) {
    if (bases && !bases.includes(choices.base)) continue
    const t0 = Date.now()
    const compiled = compileComposition(buildAmigurumiProgram(choices))
    const cute = compiled.cute!
    console.log(`${label.padEnd(18)} ${compiled.geometryHash.slice(0, 8)}  ${cute.summary}  (${((Date.now() - t0) / 1000).toFixed(0)} s)`)
    for (const f of cute.failures) console.log(`    - ${f}`)
    if (dir) writeFileSync(path.join(dir, `${label}.json`), JSON.stringify({ label, hash: compiled.geometryHash.slice(0, 8), problems: compiled.problems.length, cute } satisfies Row, null, 1))
  }
}

function markdown(file: string, dir: string): void {
  const order = presets().map((p) => p.label)
  const rows: Row[] = readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => JSON.parse(readFileSync(path.join(dir, f), 'utf8')) as Row)
  rows.sort((a, b) => order.indexOf(a.label) - order.indexOf(b.label))
  const L: string[] = []
  L.push('# Cute report: every amigurumi preset (cute-check-1026)', '')
  L.push('Generated by `apps/web/scripts/loom-cute-report.ts` from the cute check every compile now carries (`CompiledComposition.cute`, `cuteCheck.ts`). Each preset is compiled exactly as the render builds it, at its default choices, and measured in a level front view (cuteMeasure.ts). A report, not a gate: no preset hash moved, no build fails.', '')
  L.push('Key: `.` pass, `x` fail (**X** a hard-rule fail), `~` colour proxy (yarn hex, not the render), `-` not measured (the toy has no such piece), blank = the rule has no range for this family. Families: Q four-legged seated, B biped animal, D doll; ball and egg are not figures and get no rules.', '')
  const fam = (f: string | null): string => (f === 'quadruped-seated' ? 'Q' : f === 'biped-animal' ? 'B' : f === 'doll' ? 'D' : '-')
  const head = ['preset', 'fam', 'pass', ...CUTE_RULES.map((_, i) => String(i + 1))]
  L.push(`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`)
  for (const r of rows) {
    const c = r.cute
    const cells = CUTE_RULES.map((rule, i) => {
      if (!c.family || !rule.ranges[c.family]) return ''
      const res = c.results.find((x) => x.n === i + 1)
      if (!res) return '-'
      if (res.pass) return res.source === 'proxy' ? '~.' : '.'
      return (res.strictness === 'hard' ? '**X**' : 'x') + (res.source === 'proxy' ? '~' : '')
    })
    const pass = c.family ? `${c.results.filter((x) => x.pass).length}/${c.results.length}` : '-'
    L.push(`| ${r.label} | ${fam(c.family)} | ${pass} | ${cells.join(' | ')} |`)
  }
  L.push('', 'Rules: ' + CUTE_RULES.map((r, i) => `${i + 1} ${r.id} (${r.strictness})`).join('; ') + '.', '')
  L.push('## Top failures per preset, in plain English', '')
  L.push('Hard first, then firm, then soft; at most six per preset. The full list is in each preset\'s JSON beside this file.', '')
  for (const r of rows) {
    const c = r.cute
    L.push(`### ${r.label} (${r.hash})`, '')
    if (!c.family) { L.push('Not a figure: no cute rules apply.', ''); continue }
    L.push(`${c.summary}.`, '')
    for (const f of c.failures.slice(0, 6)) L.push(`- ${f}`)
    if (c.failures.length > 6) L.push(`- and ${c.failures.length - 6} more`)
    if (c.measured.notes.length) L.push(`- notes: ${c.measured.notes.join('; ')}`)
    L.push('')
  }
  writeFileSync(file, L.join('\n'))
  console.log(`wrote ${file} (${rows.length} presets)`)
}

const md = arg('md')
if (md) markdown(md, arg('json')!)
else run()
